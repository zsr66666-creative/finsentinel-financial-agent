"""Account endpoints and closed-by-default API authorization in account mode."""
import os
import secrets
import threading
import time
from collections import OrderedDict, deque
from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import JSONResponse,Response
from pydantic import BaseModel,ConfigDict,Field
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy import text
from .service import Accounts

class Payload(BaseModel): model_config=ConfigDict(extra='forbid')
class Login(Payload):
    username:str=Field(max_length=128)
    password:str=Field(max_length=128)
class Password(Payload):
    current_password:str=Field(max_length=128)
    new_password:str=Field(min_length=12,max_length=128)
class Profile(Payload):
    nickname:str=Field(min_length=1,max_length=24)
    avatar:str|None=Field(default=None,max_length=1400000)
class Create(Payload):
    username:str
    password:str=Field(min_length=12,max_length=128)
    role:str
    nickname:str=Field(min_length=1,max_length=24)
class Update(Payload):
    enabled:bool|None=None
    role:str|None=None
    password:str|None=Field(default=None,min_length=12,max_length=128)

class LoginLimiter:
    """Bounded process-local global/IP/account windows; proxy trust belongs to uvicorn."""
    def __init__(self):self.lock=threading.Lock();self.buckets=OrderedDict();self.global_attempts=deque()
    def check(self,ip,username):
        now=time.monotonic()
        with self.lock:
            while self.global_attempts and self.global_attempts[0]<now-60:self.global_attempts.popleft()
            for key in list(self.buckets):
                if self.buckets[key][-1]<now-300:del self.buckets[key]
            keys=[('ip',ip),('user',username[:128])]
            if len(self.global_attempts)>=100 or any(len(self.buckets.get(k,()))>=10 for k in keys):raise HTTPException(429,'login_rate_limit')
            self.global_attempts.append(now)
            for key in keys:
                bucket=self.buckets.setdefault(key,deque(maxlen=10));bucket.append(now);self.buckets.move_to_end(key)
            while len(self.buckets)>2048:self.buckets.popitem(last=False)

def wire_auth(app,store):
    enabled=os.getenv('AUTH_ENABLED','false').lower()=='true'
    app.state.auth_enabled=enabled
    if not enabled:return
    secure=os.getenv('AUTH_COOKIE_SECURE','true').lower()=='true'
    cookie='__Host-finsentinel_session' if secure else 'finsentinel_session'
    origin=os.getenv('AUTH_ORIGIN','')
    if not origin or (secure and not origin.startswith('https://')):raise ValueError('AUTH_ORIGIN must be configured; secure cookies require HTTPS')
    service=Accounts(getattr(store,'engine',None));app.state.accounts=service
    limiter=LoginLimiter();router=APIRouter(prefix='/api/v1/auth')
    def error(status,detail):return JSONResponse({'detail':detail},status_code=status,headers={'Cache-Control':'no-store'})
    @app.middleware('http')
    async def protect(request,call_next):
        path=request.url.path;write=request.method not in ('GET','HEAD','OPTIONS')
        if path=='/health':
            try:
                with service.engine.connect() as connection:connection.execute(text('SELECT 1'))
                return JSONResponse({'status':'ok'})
            except Exception:return JSONResponse({'status':'unavailable'},status_code=503)
        if not path.startswith('/api/'):
            # Disable autogenerated schema/docs while account mode is active.
            if path in ('/docs','/redoc','/openapi.json'):return error(404,'not_found')
            return await call_next(request)
        # Explicit machine credential is valid only for the source-ingestion namespace.
        namespace='/api/v1/admin/source-ingestion/tasks'
        machine=os.getenv('INGESTION_ADMIN_TOKEN','')
        auth=request.headers.get('authorization','')
        if (path==namespace or path.startswith(namespace+'/')) and len(machine)>=32 and secrets.compare_digest(auth.encode(),('Bearer '+machine).encode()):
            return await call_next(request)
        if write and request.headers.get('origin')!=origin:return error(403,'origin_invalid')
        if path=='/api/v1/auth/login' and request.method=='POST':
            try:response=await call_next(request)
            except (SQLAlchemyError,AttributeError):return error(503,'auth_store_unavailable')
            response.headers['Cache-Control']='no-store';return response
        try:session=service.session(request.cookies.get(cookie))
        except (SQLAlchemyError,AttributeError):return error(503,'auth_store_unavailable')
        if not session:return error(401,'authentication_required')
        request.state.session=session
        if write and not secrets.compare_digest(request.headers.get('x-csrf-token',''),session['csrf_token']):return error(403,'csrf_invalid')
        if session['user']['must_change_password'] and path not in ('/api/v1/auth/session','/api/v1/auth/password','/api/v1/auth/logout'):return error(403,'password_change_required')
        role=session['user']['role']
        admin=path.startswith('/api/v1/admin/') or path.startswith('/api/v1/observability') or path.startswith('/api/v1/auth/users')
        reviewer=write and (path.endswith('/financial-reviews') or path.endswith('/feedback'))
        if write and (path in ('/api/v1/alerts/evaluate','/api/v1/alerts/events/evaluate') or path.startswith('/api/v1/evals/')):admin=True
        if admin and role!='admin':return error(403,'admin_required')
        if reviewer and role not in ('reviewer','admin'):return error(403,'reviewer_required')
        try:response=await call_next(request)
        except (SQLAlchemyError,AttributeError):return error(503,'auth_store_unavailable')
        response.headers['Cache-Control']='no-store'
        response.headers['X-Content-Type-Options']='nosniff'
        return response
    def run(operation):
        try:return operation()
        except ValueError as exc:raise HTTPException(401 if str(exc)=='authentication_required' else 403 if str(exc)=='admin_required' else 409 if str(exc) in ('last_admin','username_exists') else 422,str(exc)) from exc
        except (SQLAlchemyError,AttributeError) as exc:raise HTTPException(503,'auth_store_unavailable') from exc
    @router.post('/login')
    def login(body:Login,request:Request):
        limiter.check(request.client.host if request.client else '',body.username)
        result=run(lambda:service.login(body.username,body.password))
        if not result:raise HTTPException(401,'invalid_credentials')
        token,envelope=result
        previous=request.cookies.get(cookie)
        if previous:run(lambda:service.logout(previous))
        response=JSONResponse(envelope,headers={'Cache-Control':'no-store'})
        response.set_cookie(cookie,token,max_age=28800,secure=secure,httponly=True,samesite='lax',path='/')
        return response
    @router.get('/session')
    def session(request:Request):return request.state.session
    @router.post('/logout',status_code=204)
    def logout(request:Request):
        run(lambda:service.logout(request.cookies.get(cookie,'')))
        response=Response(status_code=204);response.delete_cookie(cookie,path='/',secure=secure,httponly=True,samesite='lax');return response
    @router.post('/password',status_code=204)
    def password(body:Password,request:Request):
        run(lambda:service.password(request.state.session['user']['id'],body.current_password,body.new_password,session_token=request.cookies.get(cookie,'')))
        response=Response(status_code=204);response.delete_cookie(cookie,path='/',secure=secure,httponly=True,samesite='lax');return response
    @router.post('/profile')
    def profile(body:Profile,request:Request):return run(lambda:service.profile(request.state.session['user']['id'],body.nickname,body.avatar,session_token=request.cookies.get(cookie,'')))
    @router.get('/users')
    def listing():return {'items':run(service.list_users)}
    @router.post('/users',status_code=201)
    def create(body:Create,request:Request):return run(lambda:service.create_user(**body.model_dump(),actor_id=request.state.session['user']['id'],session_token=request.cookies.get(cookie,'')))
    @router.post('/users/{user_id}')
    def update(user_id:str,body:Update,request:Request):
        changes=body.model_dump(exclude_unset=True)
        if not changes or any(v is None for v in changes.values()):raise HTTPException(422,'invalid_update')
        return run(lambda:service.update_user(user_id,changes,request.state.session['user']['id'],session_token=request.cookies.get(cookie,'')))
    app.include_router(router)
